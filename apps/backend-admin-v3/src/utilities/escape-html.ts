// Escapes text for HTML element content and quoted attribute values. Anything a user or admin typed
// that ends up inside an email's HTML must go through this.
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}
